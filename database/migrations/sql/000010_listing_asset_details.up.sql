CREATE TABLE listing_asset_details (
    listing_id uuid NOT NULL,
    management_status text NOT NULL DEFAULT 'DRAFT',
    asset_type text,
    public_area_label text,
    area_square_meters numeric(8,2),
    advertised_deposit numeric(18,2),
    bedrooms integer,
    bathrooms integer,
    furnishing text,
    amenity_ids text[] NOT NULL DEFAULT '{}',
    rules text[] NOT NULL DEFAULT '{}',
    electricity_offer text,
    water_offer text,
    service_offer text,
    minimum_term_months integer,
    available_from date,
    bathroom_arrangement text,
    max_occupants integer,
    floor_label text,
    CONSTRAINT pk_listing_asset_details PRIMARY KEY (listing_id),
    CONSTRAINT fk_listing_asset_details_listing FOREIGN KEY (listing_id) REFERENCES listings(listing_id) ON DELETE NO ACTION,
    CONSTRAINT ck_listing_asset_details_management_status CHECK (management_status IN ('DRAFT', 'ACTIVE')),
    CONSTRAINT ck_listing_asset_details_area CHECK (area_square_meters IS NULL OR area_square_meters > 0),
    CONSTRAINT ck_listing_asset_details_deposit CHECK (advertised_deposit IS NULL OR advertised_deposit >= 0),
    CONSTRAINT ck_listing_asset_details_bedrooms CHECK (bedrooms IS NULL OR bedrooms BETWEEN 0 AND 100),
    CONSTRAINT ck_listing_asset_details_bathrooms CHECK (bathrooms IS NULL OR bathrooms BETWEEN 0 AND 100),
    CONSTRAINT ck_listing_asset_details_min_term CHECK (minimum_term_months IS NULL OR minimum_term_months BETWEEN 1 AND 600),
    CONSTRAINT ck_listing_asset_details_bathroom_arrangement CHECK (bathroom_arrangement IS NULL OR bathroom_arrangement IN ('PRIVATE', 'SHARED')),
    CONSTRAINT ck_listing_asset_details_max_occupants CHECK (max_occupants IS NULL OR max_occupants BETWEEN 1 AND 100),
    CONSTRAINT ck_listing_asset_details_amenity_count CHECK (cardinality(amenity_ids) <= 100),
    CONSTRAINT ck_listing_asset_details_rule_count CHECK (cardinality(rules) <= 100)
);
